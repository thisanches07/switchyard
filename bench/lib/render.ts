// Markdown for the published benchmark tables and each run's summary.md (spec 012, AC-6..AC-9).
// Every number printed here comes from a run folder; with no run the output says so.
import {
  evaluateRun,
  type PassStats,
  type RunData,
  type RunEvaluation,
  type ScenarioResult,
  type TargetResult,
} from "./evaluate.ts";
import type { Percentiles, TrendStats } from "./k6-summary.ts";
import type { ExcludedRun, LoadedRuns } from "./runs.ts";
import type { ServerOverhead } from "./types.ts";

/** `bench/target-issues.json`: the GitHub issue opened for each missed target (AC-9). */
export interface TargetIssues {
  runs: Record<string, Partial<Record<TargetResult["id"], string>>>;
}

export const GENERATED_NOTE =
  "<!-- Generated by `pnpm bench:report` from bench/results/. Do not edit by hand. -->";

const TARGET_TEXT = {
  T1: "T1: p95 gateway overhead below 15 ms (`no-cache`, client-side)",
  T2: "T2: at least 99 % success with a primary failing 30 % of the time (`chaos`)",
};

export interface Batch {
  key: string;
  runs: { data: RunData; evaluation: RunEvaluation }[];
  /** Index in `runs` of the median run (by T1 value; runs without one sort last). */
  median: number;
}

/** Runs with the same commit, config hash and CPU are repetitions of one measurement. */
export function batchesOf(runs: readonly RunData[]): Batch[] {
  const groups = new Map<string, RunData[]>();
  for (const data of [...runs].sort((a, b) => a.id.localeCompare(b.id))) {
    const env = data.environment;
    const key = `${env.git.commit}|${env.configHash}|${env.host.cpuModel}`;
    groups.set(key, [...(groups.get(key) ?? []), data]);
  }
  const batches = [...groups.entries()].map(([key, members]) => {
    const evaluated = members.map((data) => ({ data, evaluation: evaluateRun(data) }));
    const t1 = (i: number) => evaluated[i]?.evaluation.targets.find((t) => t.id === "T1")?.value;
    const order = evaluated
      .map((_, i) => i)
      .sort((a, b) => (t1(a) ?? Number.POSITIVE_INFINITY) - (t1(b) ?? Number.POSITIVE_INFINITY));
    return { key, runs: evaluated, median: order[Math.floor((order.length - 1) / 2)] ?? 0 };
  });
  // Newest batch first (by its latest run id).
  return batches.sort((a, b) => lastId(b).localeCompare(lastId(a)));
}

function lastId(batch: Batch): string {
  return batch.runs.at(-1)?.data.id ?? "";
}

const num = (value: number | null | undefined, digits = 1) =>
  value === null || value === undefined || !Number.isFinite(value) ? "n/a" : value.toFixed(digits);
const ms = (value: number | null | undefined) => (value == null ? "n/a" : `${num(value)} ms`);
const gib = (bytes: number | null | undefined) =>
  bytes == null ? "n/a" : `${(bytes / 1024 ** 3).toFixed(1)} GiB`;

export function targetCell(target: TargetResult, issues: TargetIssues, runId: string): string {
  const value =
    target.value === null
      ? "not measured"
      : target.unit === "ms"
        ? ms(target.value)
        : `${num(target.value, 2)} %`;
  if (target.status === "met") return `${value}: **met**`;
  if (target.status === "missed") {
    const issue = issues.runs[runId]?.[target.id];
    return issue
      ? `${value}: **missed** ([issue](${issue}))`
      : `${value}: **missed**, issue required (AC-9)`;
  }
  return `${value}: not evaluated (${target.reason ?? "no data"})`;
}

function row(cells: string[]): string {
  return `| ${cells.join(" | ")} |`;
}

function latencyCells(stats: TrendStats | Percentiles | null): string[] {
  return [ms(stats?.p50), ms(stats?.p95), ms(stats?.p99)];
}

function passRow(scenario: string, label: string, pass: PassStats | null, extra: string): string {
  return row([
    scenario,
    label,
    ...latencyCells(pass?.latency ?? null),
    pass ? num(pass.achievedRate) : "n/a",
    pass ? `${pass.ok} / ${pass.failed + pass.rejected}` : "n/a",
    extra,
  ]);
}

function serverRow(scenario: string, server: ServerOverhead | null): string {
  if (!server || server.p95 === null) {
    const reason = server?.reason ?? "not collected";
    return row([
      scenario,
      "overhead, server-side",
      "n/a",
      "n/a",
      "n/a",
      "",
      "",
      `not available (${reason})`,
    ]);
  }
  return row([
    scenario,
    "overhead, server-side",
    ms(server.p50),
    ms(server.p95),
    ms(server.p99),
    "",
    "",
    "",
  ]);
}

function scenarioRows(s: ScenarioResult): string[] {
  const rows: string[] = [];
  const status = s.status === "passed" ? "" : `**${s.status}**`;
  switch (s.name) {
    case "no-cache":
      rows.push(passRow(s.name, "gateway", s.gateway, status));
      rows.push(passRow(s.name, "direct baseline", s.direct, ""));
      rows.push(
        row([s.name, "overhead, client-side", ...latencyCells(s.clientOverhead), "", "", ""]),
      );
      rows.push(serverRow(s.name, s.serverOverhead));
      break;
    case "exact-cache": {
      const ratio =
        s.cacheHitRatio === null
          ? "hit ratio not measured"
          : `hit ratio ${num(s.cacheHitRatio * 100, 2)} %`;
      rows.push(
        passRow(
          s.name,
          "gateway (cache hits)",
          s.gateway,
          [status, ratio].filter(Boolean).join("; "),
        ),
      );
      rows.push(serverRow(s.name, s.serverOverhead));
      break;
    }
    case "streaming":
      rows.push(passRow(s.name, "gateway, total", s.gateway, status));
      rows.push(
        row([s.name, "gateway, TTFB", ...latencyCells(s.gateway?.ttfb ?? null), "", "", ""]),
      );
      rows.push(passRow(s.name, "direct, total", s.direct, ""));
      rows.push(row([s.name, "direct, TTFB", ...latencyCells(s.direct?.ttfb ?? null), "", "", ""]));
      rows.push(
        row([
          s.name,
          "TTFB overhead, client-side",
          ...latencyCells(s.clientTtfbOverhead),
          "",
          "",
          "",
        ]),
      );
      rows.push(serverRow(s.name, s.serverOverhead));
      break;
    case "rate-limited":
      rows.push(passRow(s.name, "admitted (200)", s.gateway, status));
      rows.push(
        row([
          s.name,
          "rejected (429)",
          ...latencyCells(s.gateway?.rejectLatency ?? null),
          "",
          "",
          "",
        ]),
      );
      break;
    case "chaos":
      rows.push(
        passRow(
          s.name,
          "gateway",
          s.gateway,
          [status, `success ${s.successPct === null ? "n/a" : `${num(s.successPct, 2)} %`}`]
            .filter(Boolean)
            .join("; "),
        ),
      );
      break;
  }
  return rows;
}

/** Per-scenario table of one run (AC-7). */
export function runTable(evaluation: RunEvaluation): string {
  const lines = [
    row(["Scenario", "Measure", "p50", "p95", "p99", "req/s", "ok / not ok", "Notes"]),
    row(["---", "---", "---:", "---:", "---:", "---:", "---:", "---"]),
  ];
  for (const scenario of evaluation.scenarios) {
    if (scenario.status === "not-run") continue;
    lines.push(...scenarioRows(scenario));
  }
  const notes = evaluation.scenarios.flatMap((s) => [
    ...s.notes.map((n) => `${s.name}: ${n}`),
    ...s.problems.map((p) => `${s.name}: ${p}`),
  ]);
  if (notes.length > 0) lines.push("", ...notes.map((n) => `- ${n}`));
  return lines.join("\n");
}

function machine(data: RunData): string {
  const e = data.environment;
  return [
    `${e.host.cpuModel} (${e.host.cpuCores} logical cores), ${gib(e.host.ramBytes)} RAM`,
    `${e.host.os.platform} ${e.host.os.release}`,
    `Docker ${e.docker.serverVersion ?? "n/a"} (${e.docker.operatingSystem ?? "n/a"}; ${e.docker.ncpu ?? "n/a"} CPUs and ${gib(e.docker.memTotalBytes)} available to Docker)`,
    `Node ${e.node}`,
    `k6 ${e.k6.version ?? "n/a"} (\`${e.k6.image}\`)`,
  ].join("; ");
}

function excludedList(excluded: readonly ExcludedRun[]): string[] {
  if (excluded.length === 0) return [];
  return [
    "",
    "Excluded from publication:",
    "",
    ...excluded.map((run) => `- \`${run.id}\`: ${run.reasons.join("; ")}`),
  ];
}

const NO_RUN = [
  "**No published run yet.** The harness is in place, but no clean benchmark run from the reference machine has been committed under `bench/results/`, so there are no results to show and the targets have not been evaluated.",
  "",
  row(["Target", "Measured", "Status"]),
  row(["---", "---", "---"]),
  row([TARGET_TEXT.T1, "not measured", "not evaluated"]),
  row([TARGET_TEXT.T2, "not measured", "not evaluated"]),
];

/** The generated results part of docs/benchmarks.md. */
export function renderDocsSection(loaded: LoadedRuns, issues: TargetIssues): string {
  const lines = [GENERATED_NOTE, ""];
  const batches = batchesOf(loaded.runs);
  if (batches.length === 0) {
    lines.push(...NO_RUN, ...excludedList(loaded.excluded));
    return lines.join("\n");
  }
  for (const [index, batch] of batches.entries()) {
    const median = batch.runs[batch.median];
    if (!median) continue;
    const env = median.data.environment;
    lines.push(
      `### ${index === 0 ? "Latest batch" : "Earlier batch"}: commit \`${env.git.commit.slice(0, 7)}\`, ${batch.runs.length} run(s)`,
      "",
      `Measured on: ${machine(median.data)}.`,
      "",
    );
    if (batch.runs.length < 3) {
      lines.push(
        `> [!NOTE]\n> ADR-0021 asks for at least three runs per published measurement; this batch has ${batch.runs.length}.`,
        "",
      );
    }
    lines.push(
      row(["Run", TARGET_TEXT.T1, TARGET_TEXT.T2, "Valid"]),
      row(["---", "---", "---", "---"]),
    );
    for (const [i, { data, evaluation }] of batch.runs.entries()) {
      const [t1, t2] = evaluation.targets;
      const label = `\`${data.id}\`${i === batch.median ? " (median)" : ""}`;
      const valid =
        evaluation.invalidReasons.length === 0
          ? "yes"
          : `no: ${evaluation.invalidReasons.join("; ")}`;
      lines.push(
        row([
          label,
          t1 ? targetCell(t1, issues, data.id) : "n/a",
          t2 ? targetCell(t2, issues, data.id) : "n/a",
          valid,
        ]),
      );
    }
    for (const [i, { data, evaluation }] of batch.runs.entries()) {
      lines.push(
        "",
        `#### Run \`${data.id}\`${i === batch.median ? " (median)" : ""}`,
        "",
        runTable(evaluation),
      );
    }
    lines.push("");
  }
  lines.push(...excludedList(loaded.excluded));
  return lines
    .join("\n")
    .replace(/\n{3,}/g, "\n\n")
    .trimEnd();
}

/** The generated benchmark part of the README: the median run of the latest batch. */
export function renderReadmeSection(loaded: LoadedRuns, issues: TargetIssues): string {
  const lines = [GENERATED_NOTE, ""];
  const latest = batchesOf(loaded.runs)[0];
  const median = latest?.runs[latest.median];
  if (!latest || !median) {
    lines.push(
      "**No published benchmark run yet.** `pnpm bench` is in place; numbers appear here only after a clean run on the reference machine is committed. The targets below are goals to verify, not results. Method: [docs/benchmarks.md](docs/benchmarks.md).",
      "",
      row(["Target", "Measured", "Status"]),
      row(["---", "---", "---"]),
      row([TARGET_TEXT.T1, "not measured", "not evaluated"]),
      row([TARGET_TEXT.T2, "not measured", "not evaluated"]),
    );
    return lines.join("\n");
  }
  const { data, evaluation } = median;
  const byName = (name: ScenarioResult["name"]) =>
    evaluation.scenarios.find((s) => s.name === name);
  const [t1, t2] = evaluation.targets;
  const noCache = byName("no-cache");
  const streaming = byName("streaming");
  const chaos = byName("chaos");
  const cache = byName("exact-cache");
  lines.push(
    `Median of ${latest.runs.length} run(s), run \`${data.id}\`, measured on ${machine(data)}. Docker Desktop gives no CPU isolation and k6 shares the host: see the [method and every run](docs/benchmarks.md).`,
    "",
    row(["Measure", "Value", "Target"]),
    row(["---", "---:", "---"]),
    row([
      "p95 gateway overhead, no cache (client-side)",
      ms(noCache?.clientOverhead?.p95),
      t1 ? targetCell(t1, issues, data.id) : "n/a",
    ]),
    row([
      "p95 gateway overhead, no cache (server-side)",
      ms(noCache?.serverOverhead?.p95),
      "cross-check",
    ]),
    row([
      "p95 time-to-first-byte overhead, streaming (client-side)",
      ms(streaming?.clientTtfbOverhead?.p95),
      "",
    ]),
    row(["p95 latency of an exact-cache hit", ms(cache?.gateway?.latency?.p95), ""]),
    row([
      "Success with the primary failing 30 % (`chaos`)",
      chaos?.successPct == null ? "n/a" : `${num(chaos.successPct, 2)} %`,
      t2 ? targetCell(t2, issues, data.id) : "n/a",
    ]),
  );
  return lines.join("\n");
}

/** summary.md of one run (also smoke and dirty runs, which are never published). */
export function renderRunSummary(data: RunData, issues: TargetIssues): string {
  const evaluation = evaluateRun(data);
  const env = data.environment;
  const publishable = env.publishable
    ? "publishable (clean full run)"
    : `not publishable: ${env.notPublishableReasons.join("; ")}`;
  const lines = [
    `# Benchmark run \`${data.id}\``,
    "",
    `- Profile: ${data.run.profile}; ${publishable}`,
    `- Commit: \`${env.git.commit}\`${env.git.dirty ? " (dirty tree)" : ""}; config ${env.configHash}`,
    `- Machine: ${machine(data)}`,
    `- Correctness: ${evaluation.scenarios
      .filter((s) => s.status !== "not-run")
      .map((s) => `${s.name} ${s.status}`)
      .join(", ")}`,
    "",
    "## Targets",
    "",
    ...evaluation.targets.map((t) => `- ${TARGET_TEXT[t.id]}: ${targetCell(t, issues, data.id)}`),
    "",
    "## Scenarios",
    "",
    runTable(evaluation),
    "",
  ];
  return lines.join("\n");
}

/** Replaces the text between `<!-- bench:<name>:start -->` and `<!-- bench:<name>:end -->`. */
export function replaceSection(text: string, name: string, content: string): string {
  const start = `<!-- bench:${name}:start -->`;
  const end = `<!-- bench:${name}:end -->`;
  const from = text.indexOf(start);
  const to = text.indexOf(end);
  if (from < 0 || to < from) throw new Error(`markers ${start} … ${end} not found`);
  return `${text.slice(0, from + start.length)}\n${content}\n${text.slice(to)}`;
}
