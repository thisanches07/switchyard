import { sql } from "drizzle-orm";
import {
  bigint,
  boolean,
  char,
  check,
  date,
  index,
  integer,
  jsonb,
  numeric,
  pgEnum,
  pgTable,
  primaryKey,
  smallint,
  text,
  timestamp,
  uuid,
} from "drizzle-orm/pg-core";
import { PII_MODES } from "../../core/pii.js";

export const keyStatus = pgEnum("api_key_status", ["active", "revoked"]);
export const piiMode = pgEnum("pii_mode", PII_MODES);

export const teams = pgTable(
  "teams",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    name: text("name").notNull().unique(),
    /** Per-minute caps across all keys of the team; NULL = no team cap (spec 005). */
    rpm: integer("rpm"),
    tpm: integer("tpm"),
    /** Monthly budget in USD; NULL = no budget (spec 007). */
    monthlyBudgetUsd: numeric("monthly_budget_usd", { precision: 12, scale: 4 }),
    /** Soft limit, percent of the budget, for the team and its keys (spec 007). */
    softLimitPct: integer("soft_limit_pct").notNull().default(80),
    createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
  },
  (table) => [
    check("teams_rpm_positive", sql`${table.rpm} > 0`),
    check("teams_tpm_positive", sql`${table.tpm} > 0`),
    check("teams_monthly_budget_usd_non_negative", sql`${table.monthlyBudgetUsd} >= 0`),
    check("teams_soft_limit_pct_range", sql`${table.softLimitPct} BETWEEN 1 AND 100`),
  ],
);

export const apiKeys = pgTable(
  "api_keys",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    teamId: uuid("team_id")
      .notNull()
      .references(() => teams.id, { onDelete: "cascade" }),
    name: text("name").notNull(),
    /** Hex SHA-256(pepper + key); the key itself is never stored (spec 004, AC-2). */
    keyHash: char("key_hash", { length: 64 }).notNull().unique(),
    keyPrefix: text("key_prefix").notNull(),
    /** NULL or empty: every model is allowed. */
    allowedModels: text("allowed_models").array(),
    status: keyStatus("status").notNull().default("active"),
    /** Per-minute limits; NULL = use limits.defaults from the config (spec 005). */
    rpm: integer("rpm"),
    tpm: integer("tpm"),
    /** PII redaction mode; NULL = pii.defaultMode from the config (spec 010). */
    piiMode: piiMode("pii_mode"),
    /** Monthly budget in USD; NULL = no budget (spec 007). */
    monthlyBudgetUsd: numeric("monthly_budget_usd", { precision: 12, scale: 4 }),
    expiresAt: timestamp("expires_at", { withTimezone: true }),
    createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
    revokedAt: timestamp("revoked_at", { withTimezone: true }),
  },
  (table) => [
    index("api_keys_team_id_idx").on(table.teamId),
    check("api_keys_rpm_positive", sql`${table.rpm} > 0`),
    check("api_keys_tpm_positive", sql`${table.tpm} > 0`),
    check("api_keys_monthly_budget_usd_non_negative", sql`${table.monthlyBudgetUsd} >= 0`),
  ],
);

/**
 * One row per admitted request (spec 006): the UsageEvent v1 fields, metadata only (ADR-0010).
 * Insert-only; no foreign keys, so events outlive the keys and teams they describe.
 */
export const usageEvents = pgTable(
  "usage_events",
  {
    /** UUIDv7 generated by the gateway: the idempotency key (ADR-0007). */
    id: uuid("id").primaryKey(),
    schemaVersion: smallint("schema_version").notNull(),
    occurredAt: timestamp("occurred_at", { withTimezone: true, mode: "string" }).notNull(),
    requestId: text("request_id").notNull(),
    teamId: uuid("team_id").notNull(),
    keyId: uuid("key_id").notNull(),
    operation: text("operation").notNull(),
    stream: boolean("stream").notNull(),
    requestedModel: text("requested_model").notNull(),
    provider: text("provider"),
    servedModel: text("served_model"),
    inputTokens: integer("input_tokens").notNull(),
    outputTokens: integer("output_tokens").notNull(),
    cachedInputTokens: integer("cached_input_tokens").notNull(),
    estimated: boolean("estimated").notNull(),
    /** Exact decimal; NULL = unknown cost (spec 007). */
    costUsd: numeric("cost_usd"),
    status: smallint("status").notNull(),
    outcome: text("outcome").notNull(),
    errorCode: text("error_code"),
    latencyMs: integer("latency_ms").notNull(),
    ttfbMs: integer("ttfb_ms"),
    attempts: integer("attempts").notNull(),
    cacheStatus: text("cache_status").notNull(),
    piiDetections: jsonb("pii_detections").$type<Record<string, number>>().notNull(),
    ingestedAt: timestamp("ingested_at", { withTimezone: true }).notNull().defaultNow(),
  },
  (table) => [
    index("usage_events_occurred_at_idx").on(table.occurredAt),
    index("usage_events_team_occurred_at_idx").on(table.teamId, table.occurredAt),
  ],
);

/**
 * Daily aggregates (spec 006), updated in the same transaction as the event insert and only for
 * rows that insert actually created. `model` is `provider/servedModel`, or the requested model
 * when no provider was called. `day` is the UTC date of `occurred_at`.
 */
export const usageDaily = pgTable(
  "usage_daily",
  {
    day: date("day", { mode: "string" }).notNull(),
    teamId: uuid("team_id").notNull(),
    keyId: uuid("key_id").notNull(),
    model: text("model").notNull(),
    requests: bigint("requests", { mode: "number" }).notNull(),
    inputTokens: bigint("input_tokens", { mode: "number" }).notNull(),
    outputTokens: bigint("output_tokens", { mode: "number" }).notNull(),
    /** Sum of known costs only. */
    costUsd: numeric("cost_usd").notNull().default("0"),
    /** Requests whose cost is unknown (costUsd null). */
    unknownCostRequests: bigint("unknown_cost_requests", { mode: "number" }).notNull().default(0),
  },
  (table) => [primaryKey({ columns: [table.day, table.teamId, table.keyId, table.model] })],
);
